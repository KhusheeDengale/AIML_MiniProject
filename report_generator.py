def fit_image_flowable(image_path, max_width=240, max_height=180):
    """Loads and scales an image to fit within max bounds preserving aspect ratio."""
    if not image_path or not os.path.exists(image_path):
        return None
    try:
        with PILImage.open(image_path) as img:
            orig_w, orig_h = img.size
        
        ratio = min(max_width / float(orig_w), max_height / float(orig_h))
        final_w = orig_w * ratio
        final_h = orig_h * ratio
        return RLImage(str(image_path), width=final_w, height=final_h)
    except Exception as e:
        print(f"[warning] Error loading image for PDF: {e}")
        return None


